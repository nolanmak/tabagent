// #20: token table for real, public, login-free sites. Opt-in, not a CI gate:
//
//   npm run build && npm run token-table
//
// Uses the real e2e harness (bridge + extension + MCP client). Read-only browsing:
// each site is granted `read` and visited with nav.goto (its act-level prompt is
// answered "once" in the side panel), then page.snapshot
// (interactive, default maxTokens), page.snapshot mode=full and page.markdown are
// called. A token is ceil(chars/4) (D23) of the unwrapped page text.
// Writes docs/token-budget.md.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { test } from "../fixture";
import { tokens, view } from "../view";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "../../docs/token-budget.md");

const SITES = [
  "https://example.com/",
  "https://en.wikipedia.org/wiki/Web_browser",
  "https://news.ycombinator.com/",
  "https://github.com/microsoft/playwright",
  "https://developer.mozilla.org/en-US/docs/Web/HTML/Element/a",
];

interface Row {
  url: string;
  interactive: number;
  truncated: boolean;
  full: number;
  fullTruncated: boolean;
  markdown: number;
  markdownTruncated: boolean;
}

test("token table for 5 real sites", async ({ h }) => {
  test.setTimeout(600_000);
  const policies = Object.fromEntries(SITES.map((u) => [new URL(u).origin, "read"]));
  await h.setPolicies(policies, { paused: false });
  const c = await h.mcp({ label: "token-table" });
  await h.ok(c, "tabs", { action: "new" });
  const rows: Row[] = [];
  for (const url of SITES) {
    // nav.goto is act-level, so on a read-only site it raises a prompt; approve that one
    // navigation through the side panel and keep the site policy at read.
    const nav = await h.answerPrompt("once", () => h.call(c, "nav.goto", { url, waitUntil: "load" }));
    if ((nav.result as { isError: boolean }).isError) throw new Error(`nav.goto ${url} failed: ${(nav.result as { text: string }).text}`);
    await new Promise((r) => setTimeout(r, 1500)); // let client-rendered content settle
    const inter = view(await h.ok(c, "page.snapshot"));
    const full = view(await h.ok(c, "page.snapshot", { mode: "full" }));
    const md = await h.ok(c, "page.markdown");
    const mdv = view(md);
    const mdText = typeof mdv.json?.markdown === "string" ? mdv.json.markdown : mdv.snap;
    if (process.env.TOKEN_TABLE_DEBUG) console.log(url, Object.keys(inter.json), Object.keys(mdv.json), md.text.slice(0, 300));
    rows.push({
      url,
      interactive: tokens(inter.snap),
      truncated: !!inter.json.truncated,
      full: tokens(full.snap),
      fullTruncated: !!full.json.truncated,
      markdown: tokens(mdText),
      markdownTruncated: !!mdv.json.truncated,
    });
  }
  const chromium = h.ctx.browser()?.version() ?? (await h.sw.evaluate(() => navigator.userAgent.match(/Chrome\/([\d.]+)/)?.[1] ?? "unknown"));
  const date = new Date().toISOString().slice(0, 10);
  const yn = (b: boolean) => (b ? "yes" : "no");
  const md = [
    "# Snapshot token budget on real sites",
    "",
    "Generated by `e2e/manual/token-table.spec.ts` (#20). Not a CI gate; numbers move with the sites.",
    "A token is `ceil(chars / 4)` (D23) of the unwrapped page text (PAGE_DATA wrappers removed).",
    "`Interactive` is `page.snapshot` with the default `maxTokens` (6000); `Truncated?` is its `truncated` flag (smart collapse or hard stop).",
    "`Full-mode` is `page.snapshot mode=full` and `Markdown` is `page.markdown`, both with their default limits; \"(truncated)\" marks their `truncated` flag.",
    "",
    "| Site | Interactive tokens | Truncated? | Full-mode tokens | Markdown tokens | Date | Chromium |",
    "| --- | ---: | :---: | ---: | ---: | --- | --- |",
    ...rows.map((r) => `| ${r.url} | ${r.interactive} | ${yn(r.truncated)} | ${r.full}${r.fullTruncated ? " (truncated)" : ""} | ${r.markdown}${r.markdownTruncated ? " (truncated)" : ""} | ${date} | ${chromium} |`),
    "",
    "## Rerun",
    "",
    "```sh",
    "npm install && npm run build",
    "npm run token-table   # rewrites this file",
    "```",
    "",
    "The spec grants each site `read` only and does read-only browsing (no logins, no form submits); each `nav.goto` prompt is answered once in the side panel.",
    "It runs only when `TABAGENT_MANUAL=1` is set; the default `npm run e2e` skips `e2e/manual/`.",
    "",
  ].join("\n");
  writeFileSync(OUT, md);
  console.log(md);
});
